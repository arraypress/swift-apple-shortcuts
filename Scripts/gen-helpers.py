#!/usr/bin/env python3
"""Compiles Helpers/*.json into Sources/AppleShortcuts/Support/HelperCatalogueData.swift.

One JSON file per helper, so adding a helper is adding a file. The files are
compiled in rather than shipped as a resource bundle: a Homebrew-symlinked
binary cannot find Bundle.module. A test fails when this file and the folder
disagree, so run this after any change to Helpers/.

    python3 Scripts/gen-helpers.py
"""
import json, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
files = sorted((root / "Helpers").glob("*.json"))
out = root / "Sources/AppleShortcuts/Support/HelperCatalogueData.swift"

entries = []
for f in files:
    text = f.read_text()
    json.loads(text)  # refuse a file that is not JSON before Swift sees it
    if '"#' in text:
        sys.exit(f"{f.name}: contains \"# — it would end the raw string")
    entries.append(f'        "{f.name}": #"""\n{text.rstrip()}\n"""#,')

swift = f'''//
//  HelperCatalogueData.swift
//  AppleShortcuts
//
//  GENERATED by Scripts/gen-helpers.py from Helpers/*.json — do not edit.
//  Compiled in, not a resource bundle: a Homebrew-symlinked binary cannot find
//  Bundle.module, and a tool that cannot find its helpers must not offer any.
//

enum HelperCatalogueData {{

    static let files: [String: String] = [
{chr(10).join(entries) if entries else ""}
    ]
}}
'''
if not entries:
    swift = swift.replace("[\n\n    ]", "[:]")
out.write_text(swift)
print(f"{len(entries)} helper(s) -> {out.relative_to(root)}")
